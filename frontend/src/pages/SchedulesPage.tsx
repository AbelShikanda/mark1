import { useEffect, useMemo, useState } from 'react';
import { api, getErrorMessage } from '../api';
import ErrorBanner from '../components/ErrorBanner';
import DataTable, { TableToolbar, type DataTableColumn } from '../components/DataTable';
import { useTableFilters } from '../hooks/useTableFilters';
import { NOTICE_INFO } from '../ui';

type Schedule = {
  id: number;
  campaign_id: number;
  campaign_name: string | null;
  start_time: string;
  end_time: string;
  status: string;
  frequency: string | null;
  repeatPost: boolean;
};

function cadence(s: Schedule): string {
  if (!s.repeatPost) return 'One-off';
  if (s.frequency === 'weekly') return 'Weekly';
  if (s.frequency === 'monthly') return 'Monthly';
  return 'Daily';
}

const CADENCE_OPTIONS = [
  { value: 'One-off', label: 'One-off' },
  { value: 'Daily', label: 'Daily' },
  { value: 'Weekly', label: 'Weekly' },
  { value: 'Monthly', label: 'Monthly' },
];

export default function SchedulesPage() {
  const [schedules, setSchedules] = useState<Schedule[]>([]);
  const [busyId, setBusyId] = useState<number | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = async () => {
    try {
      const res = await api.get<Schedule[]>('/schedules');
      setSchedules(Array.isArray(res.data) ? res.data : []);
    } catch (err) {
      setError(getErrorMessage(err));
    }
  };

  useEffect(() => {
    load();
  }, []);

  const statusOptions = useMemo(
    () =>
      Array.from(new Set(schedules.map((schedule) => schedule.status).filter(Boolean)))
        .sort((a, b) => a.localeCompare(b))
        .map((value) => ({ value, label: value })),
    [schedules],
  );

  const table = useTableFilters<Schedule>(
    schedules,
    (schedule) => `${schedule.campaign_name ?? ''} ${schedule.start_time} ${schedule.end_time} ${cadence(schedule)}`,
    [
      {
        key: 'campaign',
        label: 'Campaign',
        getValue: (schedule) => schedule.campaign_name ?? `Campaign #${schedule.campaign_id}`,
      },
      { key: 'cadence', label: 'Cadence', type: 'select', options: CADENCE_OPTIONS, getValue: cadence },
      { key: 'status', label: 'Status', type: 'select', options: statusOptions, getValue: (schedule) => schedule.status },
    ],
  );

  const clear = async (schedule: Schedule) => {
    if (!window.confirm(`Remove the schedule for “${schedule.campaign_name ?? 'campaign'}”? The campaign will become manual-only.`)) return;
    setError(null);
    setBusyId(schedule.id);
    try {
      await api.delete(`/schedules/${schedule.id}`);
      await load();
    } catch (err) {
      setError(getErrorMessage(err));
    } finally {
      setBusyId(null);
    }
  };

  const columns: DataTableColumn<Schedule>[] = [
    {
      key: 'campaign',
      header: 'Campaign',
      filter: { type: 'text' },
      cell: (schedule) => <span className="font-medium">{schedule.campaign_name ?? `Campaign #${schedule.campaign_id}`}</span>,
    },
    { key: 'start', header: 'Next run starts', cell: (schedule) => schedule.start_time },
    { key: 'end', header: 'Window ends', cell: (schedule) => schedule.end_time },
    {
      key: 'cadence',
      header: 'Cadence',
      filter: { type: 'select', options: CADENCE_OPTIONS, placeholder: 'All cadences' },
      cellClassName: 'text-xs',
      cell: (schedule) => cadence(schedule),
    },
    {
      key: 'status',
      header: 'Status',
      filter: { type: 'select', options: statusOptions, placeholder: 'All statuses' },
      cellClassName: 'text-xs text-slate-500 dark:text-slate-400',
      cell: (schedule) => schedule.status,
    },
    {
      key: 'actions',
      header: 'Actions',
      cell: (schedule) => (
        <button
          onClick={() => clear(schedule)}
          disabled={busyId === schedule.id}
          className="rounded border border-amber-300 px-2 py-1 text-xs text-amber-700 hover:bg-amber-50 disabled:opacity-40 dark:border-amber-800 dark:text-amber-300 dark:hover:bg-amber-950/50"
        >
          {busyId === schedule.id ? 'Clearing…' : 'Clear schedule'}
        </button>
      ),
    },
  ];

  return (
    <div className="space-y-4">
      <h1 className="text-2xl font-bold">Schedules</h1>
      <ErrorBanner message={error} onDismiss={() => setError(null)} />

      <div className={NOTICE_INFO}>
        Schedules are generated by campaigns. Set the start time, repeat frequency and run window on the
        Campaigns page; overlapping slots are pushed to the next free time automatically.
      </div>

      <TableToolbar
        search={table.search}
        onSearch={table.setSearch}
        placeholder="Search campaign"
        count={table.count}
        total={table.total}
        onClear={table.clearFilters}
        isFiltered={table.isFiltered}
      />

      <DataTable
        columns={columns}
        rows={table.filtered}
        rowKey={(schedule) => schedule.id}
        filters={table.values}
        onFilterChange={table.setFilter}
        emptyMessage={schedules.length === 0 ? 'No scheduled campaigns yet. Create one on the Campaigns page.' : 'No schedules match the current filters.'}
      />
    </div>
  );
}

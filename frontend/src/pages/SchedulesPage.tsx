import { useEffect, useState } from 'react';
import { api, getErrorMessage } from '../api';
import ErrorBanner from '../components/ErrorBanner';

type Schedule = {
  id: number;
  campaign_id: number;
  campaign_name: string | null;
  start_time: string;
  end_time: string;
  status: string;
  frequency: string | null;
  repeatPost: boolean;
};

function cadence(s: Schedule): string {
  if (!s.repeatPost) return 'One-off';
  if (s.frequency === 'weekly') return 'Weekly';
  if (s.frequency === 'monthly') return 'Monthly';
  return 'Daily';
}

export default function SchedulesPage() {
  const [schedules, setSchedules] = useState<Schedule[]>([]);
  const [busyId, setBusyId] = useState<number | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = async () => {
    try {
      const res = await api.get<Schedule[]>('/schedules');
      setSchedules(Array.isArray(res.data) ? res.data : []);
    } catch (err) {
      setError(getErrorMessage(err));
    }
  };

  useEffect(() => {
    load();
  }, []);

  const clear = async (schedule: Schedule) => {
    if (!window.confirm(`Remove the schedule for “${schedule.campaign_name ?? 'campaign'}”? The campaign will become manual-only.`)) return;
    setError(null);
    setBusyId(schedule.id);
    try {
      await api.delete(`/schedules/${schedule.id}`);
      await load();
    } catch (err) {
      setError(getErrorMessage(err));
    } finally {
      setBusyId(null);
    }
  };

  return (
    <div className="space-y-4">
      <h1 className="text-2xl font-bold">Schedules</h1>
      <ErrorBanner message={error} onDismiss={() => setError(null)} />

      <div className="rounded border border-blue-200 bg-blue-50 p-3 text-sm text-blue-800">
        Schedules are generated by campaigns. Set the start time, repeat frequency and run window on the
        Campaigns page; overlapping slots are pushed to the next free time automatically.
      </div>

      <table className="w-full border-collapse border border-slate-200 rounded-lg">
        <thead>
          <tr className="bg-slate-100 text-left text-xs uppercase text-slate-500">
            <th className="p-3 border-b">Campaign</th>
            <th className="p-3 border-b">Next run starts</th>
            <th className="p-3 border-b">Window ends</th>
            <th className="p-3 border-b">Cadence</th>
            <th className="p-3 border-b">Status</th>
            <th className="p-3 border-b">Actions</th>
          </tr>
        </thead>
        <tbody>
          {schedules.map((s) => (
            <tr key={s.id} className="border-b">
              <td className="p-3">{s.campaign_name ?? `Campaign #${s.campaign_id}`}</td>
              <td className="p-3">{s.start_time}</td>
              <td className="p-3">{s.end_time}</td>
              <td className="p-3 text-xs">{cadence(s)}</td>
              <td className="p-3 text-slate-500 text-xs">{s.status}</td>
              <td className="p-3">
                <button
                  onClick={() => clear(s)}
                  disabled={busyId === s.id}
                  className="rounded border border-amber-300 px-2 py-1 text-xs text-amber-700 hover:bg-amber-50 disabled:opacity-40"
                >
                  {busyId === s.id ? 'Clearing…' : 'Clear schedule'}
                </button>
              </td>
            </tr>
          ))}
          {schedules.length === 0 && (
            <tr><td colSpan={6} className="p-4 text-center text-slate-400">No scheduled campaigns yet. Create one on the Campaigns page.</td></tr>
          )}
        </tbody>
      </table>
    </div>
  );
}
